String _hex(SwatchColor color) {
  return '#${color.hex.toRadixString(16).padLeft(8, '0').substring(2).toUpperCase()}';
}

ProductVariant _v(String size, SwatchColor color, int stock) {
  return ProductVariant(
    size: size,
    color: color.name,
    colorHex: _hex(color),
    stock: stock,
  );
}

Product _p({
  required String id,
  required String name,
  required String sku,
  required ApparelCategory category,
  required String brand,
  required double price,
  required List<String> images,
  required List<ProductVariant> variants,
}) {
  return Product(
    id: id,
    name: name,
    sku: sku,
    category: category,
    brand: brand,
    price: price,
    images: images,
    variants: variants,
  );
}

